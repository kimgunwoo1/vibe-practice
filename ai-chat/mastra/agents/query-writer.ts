import { Agent } from "@mastra/core/agent";

// 사용자 질문을 사업안내에 쓰인 말로 된 검색어로 바꾼다 (mastra/prefetch.ts에서 씀).
// 질문을 그대로 검색하면 "활동지원사 신청서"처럼 엉뚱한 쪽이 나와서, 상담 에이전트가 검색을 다시 하느라 느려졌다.
// 빠르고 싼 Haiku로 1초 안팎에 끝낸다.
export const queryWriter = new Agent({
  id: "query-writer",
  name: "검색어 작성",
  instructions: `
사용자 질문을 공식 사업안내 문서에서 찾기 좋은 검색어 2개로 바꿉니다.
- 문서에 쓰이는 행정 용어를 씁니다. 예: 활동지원급여, 신규신청, 수급자격, 서비스 지원 종합조사, 본인부담금, 월 한도액, 근로지원인, 수행기관, 표준사업장 인증
- 첫째 줄은 질문의 핵심을, 둘째 줄은 같은 내용을 다른 낱말로 씁니다.
- 이전 질문이 함께 주어지면 그 맥락을 반영합니다.
- 한 줄에 검색어 하나씩, 두 줄만 씁니다. 다른 말은 쓰지 않습니다.
`.trim(),
  model: "anthropic/claude-haiku-5-5",
});
